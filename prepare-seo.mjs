import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = dirname(fileURLToPath(import.meta.url));
const url = new URL(process.argv[2] || process.env.SITE_URL || 'http://localhost');
if (url.protocol !== 'https:' || url.hostname === 'localhost' || url.username || url.password || url.search || url.hash) throw new Error('Provide the public HTTPS deployment URL: npm run seo -- https://your-domain.com/');
const base = url.href.replace(/\/?$/, '/');
const imageArg = process.argv[3];
if (!imageArg || !/\.(png|jpe?g)$/i.test(imageArg)) throw new Error('Provide a PNG/JPG social image path: npm run seo -- https://your-domain.com/ assets/social-card.png');
const imagePath = join(root, imageArg);
if (!imagePath.startsWith(root + '\\') && !imagePath.startsWith(root + '/')) throw new Error('Image must be inside this project.');
await readFile(imagePath);
const image = new URL(imageArg.replaceAll('\\', '/'), base).href;
const escape = value => value.replaceAll('&', '&amp;').replaceAll('"', '&quot;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
let html = await readFile(join(root, 'index.html'), 'utf8');
html = html.replace(/\n  <!-- generated-seo:start -->[\s\S]*?<!-- generated-seo:end -->/g, '');
const tags = `\n  <!-- generated-seo:start -->\n  <link rel="canonical" href="${escape(base)}">\n  <meta property="og:url" content="${escape(base)}">\n  <meta property="og:image" content="${escape(image)}">\n  <meta property="og:image:alt" content="Rivaan’s in Ichalkaranji — Good food. Better company.">\n  <meta name="twitter:image" content="${escape(image)}">\n  <!-- generated-seo:end -->`;
html = html.replace('</head>', `${tags}\n</head>`);
const match = html.match(/<script id="restaurant-schema" type="application\/ld\+json">([\s\S]*?)<\/script>/);
const schema = JSON.parse(match[1]); schema.url = base; schema.image = image;
html = html.replace(match[0], `<script id="restaurant-schema" type="application/ld+json">${JSON.stringify(schema).replaceAll('<', '\\u003c')}</script>`);
await writeFile(join(root, 'index.html'), html);
await writeFile(join(root, 'sitemap.xml'), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"><url><loc>${escape(base)}</loc></url></urlset>\n`);
await writeFile(join(root, 'robots.txt'), `User-agent: *\nAllow: /\nSitemap: ${base}sitemap.xml\n`);
console.log('Canonical URL, social tags, schema URL, robots.txt and sitemap.xml updated.');
